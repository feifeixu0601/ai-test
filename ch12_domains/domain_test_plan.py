# ========== 生成测试方案 ==========

def generate_plan(domain):
    """为指定方向生成测试方案"""
    if domain not in test_plans:
        print(f"未知方向：{domain}")
        return

    plan = test_plans[domain]

    print(f"\n{'=' * 60}")
    print(f"{domain} 测试方案")
    print(f"{'=' * 60}")

    print(f"\n  典型任务：{'、'.join(plan['典型任务'])}")
    print(f"  核心指标：{'、'.join(plan['核心指标'])}")

    total_cases = 0

    for dimension, info in plan["测试维度"].items():
        print(f"\n  {'─' * 50}")
        print(f"  【{dimension}】")
        print(f"  描述：{info['描述']}")
        print(f"  样本数建议：{info['样本数建议']}")
        print(f"  用例方向：")

        for direction in info["用例方向"]:
            print(f"    - {direction}")

        total_cases += len(info["用例方向"])

    print(f"\n  {'─' * 50}")
    print(f"  测试维度总数：{len(plan['测试维度'])}")
    print(f"  最少用例数：约 {total_cases} 个（每个方向至少 1 个样本）")

    return plan


